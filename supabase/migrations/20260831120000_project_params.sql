-- Исходные данные опытов, у которых своя расчётная схема.
--
-- Экспресс-опробование, поинтервальное нагнетание и налив в шурф задаются не
-- дебитом и журналом «время — понижение», а своим набором величин: геометрией
-- скважины, ступенями давления, размерами шурфа. Колонка на каждую величину
-- дала бы полтора десятка полей, из которых у любого журнала заполнена треть.
--
-- Поэтому набор едет одним JSON, разобранным по видам ОФР на клиенте
-- (db/params.js). Числа в нём в базовых единицах — метры, минуты, м³/сут, м³,
-- м², паскали, — как и всё остальное в этой таблице.
--
-- Тип text, а не jsonb: сервер в это поле не заглядывает, а клиент хранит его
-- строкой в SQLite. Приводить туда и обратно значило бы менять форму данных
-- на каждой синхронизации ради запросов, которых никто не пишет.

alter table public.projects
  add column params text;
