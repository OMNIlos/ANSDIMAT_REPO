-- Понижение на момент остановки насоса у каждой скважины куста.
--
-- До этого оно было одно на весь журнал (projects.final_drawdown). Одиночной
-- откачке этого хватает: журнал там один. У куста журналов пара на каждую
-- скважину, и понижение на остановке своё у каждой — опытная садится на
-- метры, дальняя наблюдательная на сантиметры.
--
-- Ноль значит «не задано»: тогда понижение берётся из последней строки
-- журнала откачки этой же скважины.

alter table public.wells
  add column final_drawdown double precision not null default 0;
