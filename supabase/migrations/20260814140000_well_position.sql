-- Положение скважины на карте.
--
-- Расстояния до опытной скважины удобнее расставлять на карте, чем набирать
-- числами: куст рисуется как есть, а расстояние считается по координатам.
-- Пусто, пока скважину туда не поставили, — поэтому колонки допускают null,
-- а не заводят ложный ноль у экватора.

alter table public.wells
  add column lat double precision,
  add column lon double precision;
