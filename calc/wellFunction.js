/**
 * Функция скважины Тейса W(u)
 *
 * W(u) — это экспоненциальный интеграл E₁(u) = ∫(e^(-x)/x)dx от u до ∞.
 *
 * Реализация прототипа была неверной: там ряд начинался с term = u и умножался
 * на -u/n², что даёт коэффициенты 1/(n!)² вместо 1/(n·n!), а слагаемые u и -u²/4
 * ещё и добавлялись отдельно — то есть считались дважды. Ошибка достигала
 * десятков процентов уже при u ≈ 0.5. Хвост u ≥ 1 приближался как e^(-u)/u,
 * что завышает W(u) примерно в полтора раза при u = 1.
 *
 * Здесь используются приближения Абрамовица — Стигана (Handbook of Mathematical
 * Functions, 5.1.53 и 5.1.56) с точностью не хуже 2·10⁻⁷ — этого достаточно
 * для гидрогеологических расчётов, где исходные данные известны хуже процента.
 */

// Постоянная Эйлера — Маскерони
const EULER_GAMMA = 0.5772156649015329;

// Коэффициенты A&S 5.1.53 для степенного ряда при 0 < x ≤ 1
const A = [-0.57721566, 0.99999193, -0.24991055, 0.05519968, -0.00976004, 0.00107857];

// Коэффициенты A&S 5.1.56 для рационального приближения при x > 1
const B = [0.2677737343, 8.6347608925, 18.059016973, 8.5733287401];
const C = [3.9584969228, 21.0996530827, 25.6329561486, 9.5733223454];

/**
 * Вычисляет функцию скважины Тейса W(u) = E₁(u)
 *
 * @param {number} u - безразмерный параметр u = r²S/(4Tt), должен быть > 0
 * @returns {number} значение W(u); NaN при недопустимом аргументе
 */
export function wellFunction(u) {
  if (!isFinite(u) || u <= 0) return NaN;

  // При очень малых u ряд вырождается в -γ - ln(u): остальные члены ниже
  // точности double
  if (u < 1e-12) {
    return -EULER_GAMMA - Math.log(u);
  }

  if (u <= 1) {
    // A&S 5.1.53: E₁(x) + ln(x) = a₀ + a₁x + a₂x² + a₃x³ + a₄x⁴ + a₅x⁵
    let poly = 0;
    for (let i = A.length - 1; i >= 0; i--) {
      poly = poly * u + A[i];
    }
    return poly - Math.log(u);
  }

  // A&S 5.1.56: x·e^x·E₁(x) = (x⁴ + b₃x³ + b₂x² + b₁x + b₀)
  //                          / (x⁴ + c₃x³ + c₂x² + c₁x + c₀)
  const num = (((u + B[3]) * u + B[2]) * u + B[1]) * u + B[0];
  const den = (((u + C[3]) * u + C[2]) * u + C[1]) * u + C[0];
  return (num / den) / (u * Math.exp(u));
}

export default wellFunction;
