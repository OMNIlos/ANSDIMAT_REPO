/**
 * Проверка sha-256 по известным векторам
 *
 * Своя реализация хеша имеет смысл, только если сходится с чужой. Векторы
 * взяты из FIPS 180-4 и из очевидных случаев, на которых спотыкается
 * дополнение блока: длина 55 байт (влезает вместе с длиной), 56 (не влезает,
 * нужен второй блок) и ровно 64.
 */

import { sha256Hex } from '../sha256';

describe('sha256Hex', () => {
  test('пустая строка', () => {
    expect(sha256Hex('')).toBe(
      'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855'
    );
  });

  test('abc — вектор из FIPS 180-4', () => {
    expect(sha256Hex('abc')).toBe(
      'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'
    );
  });

  test('сообщение длиной в два блока — вектор из FIPS 180-4', () => {
    expect(
      sha256Hex('abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq')
    ).toBe('248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1');
  });

  test('границы дополнения блока', () => {
    // 55 байт: длина сообщения ещё влезает в тот же блок
    expect(sha256Hex('a'.repeat(55))).toBe(
      '9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318'
    );
    // 56 байт: нужен ещё один блок под длину
    expect(sha256Hex('a'.repeat(56))).toBe(
      'b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a'
    );
    // Ровно блок
    expect(sha256Hex('a'.repeat(64))).toBe(
      'ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb'
    );
  });

  test('кириллица считается по байтам UTF-8', () => {
    // Названия журналов почти всегда кириллические, и сумма по ним должна
    // сходиться с любой стандартной реализацией
    expect(sha256Hex('Куст №3')).toBe(
      '3f8af53a2de0dae785a69b24299e81e50f04272beed3f18deebeeea122973cc0'
    );
  });

  test('суррогатная пара кодируется четырьмя байтами, а не двумя тройками', () => {
    expect(sha256Hex('🌊')).toBe(
      '8db6bed4743d5a6159e0742df0fded8377d1250420aeda292e41ffa20eba806e'
    );
  });

  test('непарный суррогат заменяется на U+FFFD', () => {
    // Иначе сумма зависела бы от того, как рантайм обошёлся с битым
    // символом, и у отправителя с получателем разошлась бы
    expect(sha256Hex('\uD800')).toBe(sha256Hex('�'));
  });

  test('длина результата всегда 64 знака', () => {
    for (const sample of ['', 'a', 'x'.repeat(1000), 'Куст №3']) {
      expect(sha256Hex(sample)).toMatch(/^[0-9a-f]{64}$/);
    }
  });
});
