/**
 * Константы формата обмена проектами
 *
 * Собраны в одном месте, потому что расходятся по трём слоям: приложение
 * пишет их в файл, `app.json` объявляет их системе, а разбор сверяет с ними
 * входящее. Разъедься они — и файл, который приложение само же создало,
 * перестанет им открываться.
 */

/** Магическая строка: отличает свой файл от произвольного JSON */
export const PROJECT_FILE_FORMAT = 'ansdimat.project';

/**
 * Версия схемы файла
 *
 * Растёт при несовместимом изменении полей `payload`. Импорт принимает свою
 * версию и все, что ниже; файл с большей версией отклоняется — разобрать
 * половину полей и выдать это за импортированный журнал хуже честного отказа.
 */
export const PROJECT_FILE_VERSION = 1;

/** Расширение без точки */
export const PROJECT_FILE_EXTENSION = 'ansdimat';

/** Тип содержимого. Объявлен в `app.json` для обеих платформ */
export const PROJECT_FILE_MIME = 'application/vnd.ansdimat.project+json';

/**
 * Идентификатор типа для iOS
 *
 * Совпадает с `UTExportedTypeDeclarations` в `app.json`. Обратный домен взят
 * от bundle identifier приложения: тип экспортируемый, владелец у него один.
 */
export const PROJECT_FILE_UTI = 'com.omnion.ansdimat.project';

/**
 * Причины, по которым файл не принят
 *
 * Код отделён от текста: сообщение переводится, а решение о том, что делать
 * дальше, принимается по коду.
 */
export const IMPORT_ERRORS = {
  /** Нет магической строки: это не файл проекта */
  NOT_ANSDIMAT: 'not-ansdimat',
  /** Файл создан более новой версией приложения */
  TOO_NEW: 'too-new',
  /** JSON не разобрался или не сошлась контрольная сумма */
  CORRUPTED: 'corrupted',
  /** Разобрался, но обязательных полей нет или они не того типа */
  INVALID: 'invalid',
  /** Не удалось прочитать с диска */
  READ_FAILED: 'read-failed',
};

/**
 * Превращает название журнала в безопасное имя файла
 *
 * Кириллица остаётся как есть — её принимают и iOS, и Android, и почта.
 * Убираются только символы, на которых спотыкаются файловые системы и
 * заголовок Content-Disposition при пересылке.
 *
 * @param {string} name - название журнала
 * @returns {string} имя файла с расширением
 */
export function suggestFileName(name) {
  const cleaned = String(name ?? '')
    .replace(/[\\/:*?"<>|]/g, ' ')
    // Точки внутри имени ломают сопоставление по pathPattern в Android:
    // фильтр рассчитан на известное число точек, и лишняя уводит файл мимо
    .replace(/\./g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    // Длинное имя обрезается: часть почтовых клиентов режет его сама, и
    // расширение при этом теряется вместе с хвостом
    .slice(0, 80)
    .trim();

  const base = cleaned || 'project';
  return base + '.' + PROJECT_FILE_EXTENSION;
}
